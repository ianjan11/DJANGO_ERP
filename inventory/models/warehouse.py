def bootstrap_default_locations():
    """Idempotently create Odoo's shared virtual locations. Returns them by key."""
    U, get = StockLocation.Usage, StockLocation._get_or_create_shared
    physical = StockLocation.get_physical_root()
    partners = get('Partners', U.VIEW)
    virtual = get('Virtual Locations', U.VIEW)
    return {
        'physical': physical,
        'vendors': get('Vendors', U.SUPPLIER, partners),
        'customers': get('Customers', U.CUSTOMER, partners),
        'inventory_loss': get('Inventory adjustment', U.INVENTORY, virtual),
        'production': get('Production', U.PRODUCTION, virtual),
        'scrap': get('Scrap', U.INVENTORY, virtual, scrap_location=True),
        'transit': get('Inter-company transit', U.TRANSIT, physical),
    }


def repair_picking_type_defaults():
    """One-off / cron repair: re-sync every warehouse's picking types and routes so each type has
    both default locations again."""
    for warehouse in Warehouse.objects.all():
        with transaction.atomic():
            warehouse._sync_picking_types()
            warehouse._sync_routes()