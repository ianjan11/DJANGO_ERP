class StockLocation(models.Model):
    class Usage(models.TextChoices):
        SUPPLIER = 'supplier', 'Vendor Location'
        VIEW = 'view', 'View'
        INTERNAL = 'internal', 'Internal Location'
        CUSTOMER = 'customer', 'Customer Location'
        INVENTORY = 'inventory', 'Inventory Loss'
        PRODUCTION = 'production', 'Production'
        TRANSIT = 'transit', 'Transit Location'

    class RemovalStrategy(models.TextChoices):
        FIFO = 'fifo', 'First In First Out (FIFO)'
        LIFO = 'lifo', 'Last In First Out (LIFO)'
        CLOSEST = 'closest', 'Closest Location'
        FEFO = 'fefo', 'First Expiry First Out (FEFO)'

    # Only these can hold quants (Odoo: stock.quant is limited to internal + transit).
    STOCKABLE_USAGES = (Usage.INTERNAL, Usage.TRANSIT)

    name = models.CharField('Location Name', max_length=128)
    complete_name = models.CharField(max_length=512, blank=True, editable=False, db_index=True)
    active = models.BooleanField(default=True)
    usage = models.CharField('Location Type', max_length=12, choices=Usage.choices,
                             default=Usage.INTERNAL, db_index=True)

    parent = models.ForeignKey('self', null=True, blank=True, on_delete=models.PROTECT,
                               related_name='children', verbose_name='Parent Location')
    parent_path = models.CharField(max_length=512, blank=True, editable=False, db_index=True)

    # Computed from the tree (nearest ancestor that is a warehouse view location).
    warehouse = models.ForeignKey(Warehouse, null=True, blank=True, editable=False,
                                  on_delete=models.SET_NULL, related_name='locations')

    # Shared virtual locations (Vendors, Customers, ...) have no company.
    company = models.ForeignKey('core.Company', null=True, blank=True,
                                on_delete=models.PROTECT, related_name='locations')

    note = models.TextField('Additional Information', blank=True)
    barcode = models.CharField(max_length=64, null=True, blank=True)

    # Physical position: corridor (X), shelves (Y), height (Z)
    posx = models.PositiveIntegerField('Corridor (X)', default=0)
    posy = models.PositiveIntegerField('Shelves (Y)', default=0)
    posz = models.PositiveIntegerField('Height (Z)', default=0)

    scrap_location = models.BooleanField('Is a Scrap Location?', default=False)
    return_location = models.BooleanField('Is a Return Location?', default=False)
    replenish_location = models.BooleanField('Replenish Location', default=False)
    removal_strategy = models.CharField(
        max_length=10, choices=RemovalStrategy.choices, blank=True,
        help_text='Blank = inherit from the parent location / product category.')

    class Meta:
        ordering = ['complete_name', 'id']
        constraints = [
            models.UniqueConstraint(
                fields=['barcode', 'company'], condition=Q(barcode__isnull=False),
                name='stock_location_barcode_company_uniq'),
        ]

    def __str__(self):
        return self.complete_name or self.name

    @property
    def is_stockable(self):
        """Quants / stock moves may only rest here if True."""
        return self.usage in self.STOCKABLE_USAGES

    # -- tree helpers ------------------------------------------------------- #
    def descendants(self, include_self=False):
        if not self.parent_path:
            return StockLocation.objects.none()
        qs = StockLocation.objects.filter(parent_path__startswith=self.parent_path)
        return qs if include_self else qs.exclude(pk=self.pk)

    def ancestors(self, include_self=False):
        ids = _path_ids(self.parent_path)
        if not include_self:
            ids = [i for i in ids if i != self.pk]
        return StockLocation.objects.filter(pk__in=ids)

    # -- shared root locations --------------------------------------------- #
    @classmethod
    def _get_or_create_shared(cls, name, usage, parent=None, **extra):
        obj = cls.objects.filter(name=name, usage=usage, parent=parent, company__isnull=True).first()
        return obj or cls.objects.create(name=name, usage=usage, parent=parent, **extra)

    @classmethod
    def get_physical_root(cls):
        return cls._get_or_create_shared('Physical Locations', cls.Usage.VIEW)

    # -- validation (Odoo enforces these in the ORM, so we do it in save()) -- #
    def _validate(self, parent):
        if parent and self.pk and (parent.pk == self.pk or self.pk in _path_ids(parent.parent_path)):
            raise ValidationError('A location cannot be its own ancestor (recursive hierarchy).')

        if parent and parent.company_id and self.company_id and parent.company_id != self.company_id:
            raise ValidationError('The company of a location must match its parent location.')

        if self.replenish_location:
            related = Q(pk__in=_path_ids(parent.parent_path) if parent else [])
            if self.parent_path:           # never startswith('') -> would match every row
                related |= Q(parent_path__startswith=self.parent_path)
            if (StockLocation.objects.filter(replenish_location=True)
                    .exclude(pk=self.pk).filter(related).exists()):
                raise ValidationError('Another parent/sub replenish location already exists; '
                                      'a replenish location cannot be nested with another.')

    def _assert_can_archive(self):
        in_use = Warehouse.objects.filter(active=True).filter(
            Q(view_location=self) | Q(lot_stock=self)).first()
        if in_use:
            raise ValidationError(
                f'You cannot archive "{self.complete_name}" because it is used by warehouse "{in_use}".')
        if self.has_stock(include_children=True):
            raise ValidationError(f'"{self.complete_name}" (or a sub-location) still holds stock.')

    def has_stock(self, include_children=False):
        from inventory.models import StockQuant
        qs = StockQuant.objects.exclude(quantity=0)
        if include_children and self.parent_path:
            return qs.filter(location__parent_path__startswith=self.parent_path).exists()
        return qs.filter(location=self).exists()

    def clean(self):
        super().clean()
        self._validate(self.parent if self.parent_id else None)

    # -- persistence -------------------------------------------------------- #
    @transaction.atomic
    def save(self, *args, **kwargs):
        if not self.barcode:
            self.barcode = None
        if self.usage not in (self.Usage.INTERNAL, self.Usage.INVENTORY):
            self.scrap_location = False    # Odoo's _onchange_usage

        creating = self._state.adding
        old = None
        if not creating:
            old = StockLocation.objects.filter(pk=self.pk).values(
                'parent_id', 'name', 'usage', 'active', 'parent_path').first()

        parent = StockLocation.objects.get(pk=self.parent_id) if self.parent_id else None
        self._validate(parent)
        if old and old['active'] and not self.active:
            self._assert_can_archive()
        if (old and old['usage'] != self.usage and self.usage not in self.STOCKABLE_USAGES
                and old['usage'] in self.STOCKABLE_USAGES and self.has_stock()):
            raise ValidationError('You cannot change the location type while it holds stock.')

        # Odoo: a view location restarts the displayed path.
        if parent and self.usage != self.Usage.VIEW:
            self.complete_name = f'{parent.complete_name}/{self.name}'
        else:
            self.complete_name = self.name

        super().save(*args, **kwargs)

        # parent_path needs the pk, so it is written right after the first save.
        new_path = f'{parent.parent_path}{self.pk}/' if parent else f'{self.pk}/'
        old_path = old['parent_path'] if old else ''
        warehouse_id = self._find_warehouse_id(new_path)
        self.parent_path, self.warehouse_id = new_path, warehouse_id
        StockLocation.objects.filter(pk=self.pk).update(parent_path=new_path, warehouse_id=warehouse_id)

        if old:
            if old['active'] != self.active:
                self.descendants().update(active=self.active)
            if (old['parent_id'], old['name'], old['usage']) != (self.parent_id, self.name, self.usage) \
                    or old_path != new_path:
                self._refresh_subtree(old_path)

    @staticmethod
    def _find_warehouse_id(path):
        ids = _path_ids(path)
        by_view = dict(Warehouse.objects.filter(view_location_id__in=ids)
                       .values_list('view_location_id', 'pk'))
        for pk in reversed(ids):           # nearest ancestor wins
            if pk in by_view:
                return by_view[pk]
        return None

    def _refresh_subtree(self, old_path):
        """Rewrite parent_path, complete_name and warehouse for every descendant."""
        if old_path and old_path != self.parent_path:
            (StockLocation.objects
             .filter(parent_path__startswith=old_path).exclude(pk=self.pk)
             .update(parent_path=Concat(
                 Value(self.parent_path, output_field=models.CharField()),
                 Substr('parent_path', len(old_path) + 1),
                 output_field=models.CharField())))

        # Ordered by path length so every parent is processed before its children.
        descendants = list(self.descendants().order_by(Length('parent_path'), 'id'))
        if not descendants:
            return
        view_of = dict(Warehouse.objects.filter(view_location_id__in=[d.pk for d in descendants])
                       .values_list('view_location_id', 'pk'))
        names = {self.pk: self.complete_name}
        whs = {self.pk: self.warehouse_id}
        for loc in descendants:
            loc.complete_name = (loc.name if loc.usage == self.Usage.VIEW
                                 else f'{names[loc.parent_id]}/{loc.name}')
            loc.warehouse_id = view_of.get(loc.pk, whs[loc.parent_id])
            names[loc.pk], whs[loc.pk] = loc.complete_name, loc.warehouse_id
        StockLocation.objects.bulk_update(descendants, ['complete_name', 'warehouse'], batch_size=500)


