"""
Odoo-style warehouses and stock locations (mirrors stock.warehouse / stock.location).

Behaviour copied from Odoo:
  * Creating a warehouse auto-creates its view location plus Stock, Input,
    Quality Control, Output and Packing Zone locations. Input / QC / Output /
    Packing are only *active* when the reception / delivery steps need them.
  * Locations are a tree with a materialised `parent_path` ("1/5/12/") so
    "everything under X" is a single indexed query.
  * `complete_name` is stored. Like Odoo, a VIEW location restarts the path, so
    you get "WH/Stock/Shelf 1" and not "Physical Locations/WH/Stock/Shelf 1".
  * `warehouse` on a location is *computed* from its position in the tree.
  * Archiving cascades down the tree; nothing is hard-deleted by cascade.

StockQuant and StockMove (bottom of file) are what make locations useful:
a move takes stock from its source location and puts it in its destination.

Picking types and routes (Odoo: _create_or_update_sequences_and_picking_types /
_create_or_update_route): a warehouse owns one Receipts, Quality Control, Storage, Pick, Pack,
Delivery, Internal, Customer Returns and Supplier Returns picking type, and two routes whose rules
are generated from reception_steps / delivery_steps and kept in sync when they change:

    reception 1 step    Vendors -> Stock                     (buy rule delivers into Stock)
    reception 2 steps   Vendors -> Input -> Stock            (storage pull + push rule)
    reception 3 steps   Vendors -> Input -> QC -> Stock      (QC and storage pull + push rules)
    delivery 1 step     Stock -> Customers
    delivery pick+ship  Stock -> Output -> Customers
    delivery 3 steps    Stock -> Packing -> Output -> Customers

Every picking type always has both default locations: _sync_picking_types() raises if a step
location is missing, and save() re-syncs whenever a type link or a default location is empty
(see _picking_types_need_repair). repair_picking_type_defaults() repairs existing data.

Not included: storage categories.
"""

from django.core.exceptions import ValidationError
from django.db import models, transaction
from django.db.models import Q, Value
from django.db.models.functions import  Concat, Length,  Substr



def _path_ids(path):
    """'1/5/12/' -> [1, 5, 12]"""
    return [int(p) for p in (path or '').split('/') if p]


# --------------------------------------------------------------------------- #
# Warehouse
# --------------------------------------------------------------------------- #
class Warehouse(models.Model):
    class ReceptionSteps(models.TextChoices):
        ONE = 'one_step', 'Receive goods directly (1 step)'
        TWO = 'two_steps', 'Receive goods in input and then stock (2 steps)'
        THREE = 'three_steps', 'Receive goods in input, then quality and then stock (3 steps)'

    class DeliverySteps(models.TextChoices):
        SHIP_ONLY = 'ship_only', 'Deliver goods directly (1 step)'
        PICK_SHIP = 'pick_ship', 'Send goods in output and then deliver (2 steps)'
        PICK_PACK_SHIP = 'pick_pack_ship', 'Pack goods, send goods in output and then deliver (3 steps)'

    name = models.CharField(max_length=128)
    active = models.BooleanField(default=True)
    sequence = models.PositiveIntegerField(default=10)
    company = models.ForeignKey('core.Company', on_delete=models.PROTECT, related_name='warehouses')
    # Odoo's "Address" is a res.partner record, not free text.
    partner = models.ForeignKey('core.Partner', null=True, blank=True, on_delete=models.SET_NULL, related_name='+')
    code = models.CharField('Short name', max_length=5, help_text='Short name used to identify your warehouse')

    reception_steps = models.CharField(max_length=20, choices=ReceptionSteps.choices, default=ReceptionSteps.ONE)
    delivery_steps = models.CharField(max_length=20, choices=DeliverySteps.choices, default=DeliverySteps.SHIP_ONLY)

    # Created automatically in save(). Nullable only because of the
    # chicken-and-egg with StockLocation.warehouse.
    _loc = dict(null=True, blank=True, editable=False, on_delete=models.PROTECT, related_name='+')
    view_location = models.OneToOneField('StockLocation', **_loc)
    lot_stock = models.OneToOneField('StockLocation', **_loc)
    wh_input_stock_loc = models.OneToOneField('StockLocation', **_loc)
    wh_qc_stock_loc = models.OneToOneField('StockLocation', **_loc)
    wh_output_stock_loc = models.OneToOneField('StockLocation', **_loc)
    wh_pack_stock_loc = models.OneToOneField('StockLocation', **_loc)

    # Picking types and routes, generated by _sync_picking_types() / _sync_routes().
    in_type = models.OneToOneField('inventory.StockPickingType', **_loc)
    qc_type = models.OneToOneField('inventory.StockPickingType', **_loc)
    store_type = models.OneToOneField('inventory.StockPickingType', **_loc)
    pick_type = models.OneToOneField('inventory.StockPickingType', **_loc)
    pack_type = models.OneToOneField('inventory.StockPickingType', **_loc)
    out_type = models.OneToOneField('inventory.StockPickingType', **_loc)
    int_type = models.OneToOneField('inventory.StockPickingType', **_loc)
    cust_return_type = models.OneToOneField('inventory.StockPickingType', **_loc)
    sup_return_type = models.OneToOneField('inventory.StockPickingType', **_loc)
    reception_route = models.OneToOneField('inventory.StockRoute', **_loc)
    delivery_route = models.OneToOneField('inventory.StockRoute', **_loc)
    del _loc

    # The nine operation-type links a warehouse owns.
    PICKING_TYPE_FIELDS = ('in_type', 'qc_type', 'store_type', 'pick_type', 'pack_type',
                           'out_type', 'int_type', 'cust_return_type', 'sup_return_type')

    class Meta:
        ordering = ['sequence', 'id']
        constraints = [
            models.UniqueConstraint(fields=['name', 'company'], name='warehouse_name_uniq'),
            models.UniqueConstraint(fields=['code', 'company'], name='warehouse_code_uniq'),
        ]

    def __str__(self):
        return self.name

    # -- location layout ---------------------------------------------------- #
    def _location_specs(self):
        """(field, name, barcode suffix, should_be_active) for each sub-location."""
        R, D = self.ReceptionSteps, self.DeliverySteps
        return [
            ('lot_stock', 'Stock', 'STOCK', True),
            ('wh_input_stock_loc', 'Input', 'INPUT', self.reception_steps != R.ONE),
            ('wh_qc_stock_loc', 'Quality Control', 'QUALITY', self.reception_steps == R.THREE),
            ('wh_output_stock_loc', 'Output', 'OUTPUT', self.delivery_steps != D.SHIP_ONLY),
            ('wh_pack_stock_loc', 'Packing Zone', 'PACKING', self.delivery_steps == D.PICK_PACK_SHIP),
        ]

    def _valid_barcode(self, barcode):
        """Odoo silently drops an auto-generated barcode that would clash."""
        clash = StockLocation.objects.filter(barcode=barcode, company_id=self.company_id).exists()
        return None if clash else barcode

    def _create_locations(self):
        root = StockLocation.get_physical_root()
        view = StockLocation.objects.create(
            name=self.code, usage=StockLocation.Usage.VIEW, parent=root,
            company_id=self.company_id, active=self.active,
        )
        # Link first, then re-save the view so its computed `warehouse` is filled
        # and every child created below picks the warehouse up automatically.
        Warehouse.objects.filter(pk=self.pk).update(view_location=view)
        self.view_location = view
        view.save()

        links = {}
        for field, name, suffix, flag in self._location_specs():
            links[field] = StockLocation.objects.create(
                name=name, usage=StockLocation.Usage.INTERNAL, parent=view,
                company_id=self.company_id, active=self.active and flag,
                barcode=self._valid_barcode(f'{self.code}-{suffix}'),
            )
        Warehouse.objects.filter(pk=self.pk).update(**links)
        for field, loc in links.items():
            setattr(self, field, loc)
        self._sync_picking_types()
        self._sync_routes()

    # -- picking types ------------------------------------------------------ #
    def _picking_type_specs(self, vendors, customers):
        """One spec per picking type. Locations follow the reception / delivery steps; types a step
        setting does not need are kept but archived (like the step locations)."""
        R, D, T = self.ReceptionSteps, self.DeliverySteps, self._picking_type_model().Code
        stock, inp, qc = self.lot_stock, self.wh_input_stock_loc, self.wh_qc_stock_loc
        out, pack = self.wh_output_stock_loc, self.wh_pack_stock_loc
        multi_in = self.reception_steps != R.ONE
        receipt_dest = inp if multi_in else stock
        store_src = qc if self.reception_steps == R.THREE else inp
        pick_dest = pack if self.delivery_steps == D.PICK_PACK_SHIP else out
        deliver_src = stock if self.delivery_steps == D.SHIP_ONLY else out
        return [
            # field, name, code, prefix, source, destination, needed?
            ('in_type', 'Receipts', T.INCOMING, 'IN', vendors, receipt_dest, True),
            ('qc_type', 'Quality Control', T.INTERNAL, 'QC', inp, qc, self.reception_steps == R.THREE),
            ('store_type', 'Storage', T.INTERNAL, 'STOR', store_src, stock, multi_in),
            ('pick_type', 'Pick', T.INTERNAL, 'PICK', stock, pick_dest, self.delivery_steps != D.SHIP_ONLY),
            ('pack_type', 'Pack', T.INTERNAL, 'PACK', pack, out, self.delivery_steps == D.PICK_PACK_SHIP),
            ('out_type', 'Delivery Orders', T.OUTGOING, 'OUT', deliver_src, customers, True),
            ('int_type', 'Internal Transfers', T.INTERNAL, 'INT', stock, stock, True),
            ('cust_return_type', 'Customer Returns', T.RETURN, 'RET-IN', customers, receipt_dest, True),
            ('sup_return_type', 'Supplier Returns', T.RETURN, 'RET-OUT', receipt_dest, vendors, True),
        ]

    @staticmethod
    def _picking_type_model():
        from inventory.models import StockPickingType
        return StockPickingType

    def _shared_partner_locations(self):
        """The shared Vendors and Customers locations."""
        U = StockLocation.Usage
        partners = StockLocation._get_or_create_shared('Partners', U.VIEW)
        vendors = StockLocation._get_or_create_shared('Vendors', U.SUPPLIER, partners)
        customers = StockLocation._get_or_create_shared('Customers', U.CUSTOMER, partners)
        return vendors, customers

    def locations_for(self, picking_type):
        """(source, destination) that this warehouse's CURRENT steps imply for one of its picking
        types. Reuses _picking_type_specs, the table that generates the types, so it can never
        disagree with the routes."""
        vendors, customers = self._shared_partner_locations()
        for field, _name, _code, _prefix, src, dest, _needed in self._picking_type_specs(vendors, customers):
            if getattr(self, f'{field}_id') == picking_type.pk:
                return src, dest
        raise ValidationError(f'"{picking_type}" is not a picking type of warehouse "{self}".')

    def _picking_types_need_repair(self):
        """True if a type link is missing or any of this warehouse's types lacks a default location."""
        if any(getattr(self, f'{field}_id') is None for field in self.PICKING_TYPE_FIELDS):
            return True
        return self.picking_types.filter(
            Q(default_source_location__isnull=True) | Q(default_dest_location__isnull=True)).exists()

    def _sync_picking_types(self):
        """Create / update the picking types for the current steps (idempotent) and guarantee that
        every type ends up with both default locations: a missing step location raises instead of
        leaving a null default. The new values are also written onto the cached type instances,
        because _sync_routes reads self.in_type.default_dest_location right after this."""
        T = self._picking_type_model()
        vendors, customers = self._shared_partner_locations()

        links = {}
        for field, name, code, prefix, src, dest, needed in self._picking_type_specs(vendors, customers):
            if src is None or dest is None:
                missing = 'source' if src is None else 'destination'
                raise ValidationError(
                    f'Warehouse "{self}": the "{name}" type has no {missing} location because a step '
                    'location is missing. Recreate it before saving.')
            vals = dict(name=f'{self.code}: {name}', code=code, sequence_prefix=f'{self.code}/{prefix}/',
                        default_source_location=src, default_dest_location=dest,
                        active=self.active and needed)
            pt = getattr(self, field)
            if pt is None:
                pt = T.objects.create(warehouse=self, **vals)
                links[field] = pt
                setattr(self, field, pt)
            else:
                T.objects.filter(pk=pt.pk).update(**vals)
                for key, value in vals.items():      # keep the cached instance in step with the DB
                    setattr(pt, key, value)
        if links:
            Warehouse.objects.filter(pk=self.pk).update(**links)

        # a completed transfer knows which type to use when it is returned
        T.objects.filter(pk=self.in_type_id).update(return_picking_type=self.sup_return_type)
        T.objects.filter(pk=self.out_type_id).update(return_picking_type=self.cust_return_type)

    # -- routes -------------------------------------------------------------- #
    def _ensure_route(self, field, name, sequence):
        from inventory.models import RouteAssignment, StockRoute
        route = getattr(self, field)
        if route is None:
            route = StockRoute.objects.create(name=name, company_id=self.company_id,
                                              sequence=sequence, active=self.active)
            Warehouse.objects.filter(pk=self.pk).update(**{field: route})
            setattr(self, field, route)
        else:
            StockRoute.objects.filter(pk=route.pk).update(name=name, sequence=sequence, active=self.active)
        RouteAssignment.objects.get_or_create(route=route, scope=RouteAssignment.Scope.WAREHOUSE, warehouse=self)
        return route

    def _upsert_rules(self, model, route, specs):
        """Update generated rules in place (found by system_key), create missing ones, and retire the
        ones the current steps no longer need."""
        keys = set()
        for spec in specs:
            keys.add(spec['system_key'])
            vals = {**spec, 'route': route, 'company_id': self.company_id}
            rule = model.objects.filter(route=route, system_key=spec['system_key']).first()
            if rule is None:
                model.objects.create(**vals)
            else:
                model.objects.filter(pk=rule.pk).update(**{k: v for k, v in vals.items() if k != 'system_key'})
        stale = model.objects.filter(route=route).exclude(system_key='').exclude(system_key__in=keys)
        if hasattr(model, 'active'):
            stale.update(active=False)
        else:
            stale.delete()

    def _sync_routes(self):
        """Generate the reception and delivery routes and their rules for the current steps.

        Reception steps need a pull AND a push rule per step (Odoo's pull_push):
          * pull: demand at the destination (a reordering rule on Stock) pulls from the step before,
            chaining back to the buy rule;
          * push: a receipt that arrives without a chain (a hand-made PO) still gets its next step.
        A chained receipt skips the push, because it already has a next move."""
        from inventory.models import StockRule, SupplyRule
        R, D, Rule = self.ReceptionSteps, self.DeliverySteps, StockRule
        stock, inp, qc = self.lot_stock, self.wh_input_stock_loc, self.wh_qc_stock_loc
        out, pack = self.wh_output_stock_loc, self.wh_pack_stock_loc
        customers = self.out_type.default_dest_location
        MTS, MTO = Rule.ProcureMethod.MAKE_TO_STOCK, Rule.ProcureMethod.MAKE_TO_ORDER

        reception = self._ensure_route('reception_route', f'{self.code}: ' + {
            R.ONE: 'Receive in 1 step', R.TWO: 'Receive in 2 steps (input + stock)',
            R.THREE: 'Receive in 3 steps (input + quality + stock)'}[self.reception_steps], 10)
        delivery = self._ensure_route('delivery_route', f'{self.code}: ' + {
            D.SHIP_ONLY: 'Deliver in 1 step (ship)', D.PICK_SHIP: 'Deliver in 2 steps (pick + ship)',
            D.PICK_PACK_SHIP: 'Deliver in 3 steps (pick + pack + ship)'}[self.delivery_steps], 20)

        def rule(key, action, src, dest, ptype, method=MTS, auto='', cancel=False):
            return dict(system_key=key, action=action, name=f'{self.code}: {src.name} → {dest.name}',
                        location_src=src, location_dest=dest, picking_type=ptype, procure_method=method,
                        auto=auto, propagate_cancel=cancel, warehouse=self, active=True)

        # reception chain: (source, destination, picking type), farthest from stock first
        rec_chain = {R.ONE: [],
                     R.TWO: [(inp, stock, self.store_type)],
                     R.THREE: [(inp, qc, self.qc_type), (qc, stock, self.store_type)]}[self.reception_steps]
        rec_rules = []
        for i, (src, dest, ptype) in enumerate(rec_chain):
            rec_rules.append(rule(f'rec_pull_{i}', Rule.Action.PULL, src, dest, ptype, MTO, cancel=True))
            rec_rules.append(rule(f'rec_push_{i}', Rule.Action.PUSH, src, dest, ptype,
                                  auto=Rule.Auto.MANUAL, cancel=True))
        self._upsert_rules(StockRule, reception, rec_rules)

        # buy rule: vendors deliver where the receipt type delivers (Stock, or Input in multi-step)
        self._upsert_rules(SupplyRule, reception, [dict(
            system_key='buy', action=SupplyRule.Action.BUY,
            location_dest=self.in_type.default_dest_location, picking_type=self.in_type)])

        # delivery chain: (source, destination, picking type, procure method); the customer end is MTO
        # so a sale pulls the earlier steps, and the first step takes from stock
        del_chain = {
            D.SHIP_ONLY: [(stock, customers, self.out_type, MTS)],
            D.PICK_SHIP: [(out, customers, self.out_type, MTO), (stock, out, self.pick_type, MTS)],
            D.PICK_PACK_SHIP: [(out, customers, self.out_type, MTO), (pack, out, self.pack_type, MTO),
                               (stock, pack, self.pick_type, MTS)],
        }[self.delivery_steps]
        self._upsert_rules(StockRule, delivery, [
            rule(f'del_pull_{i}', Rule.Action.PULL, src, dest, ptype, method)
            for i, (src, dest, ptype, method) in enumerate(del_chain)])

    def _sync_step_locations(self):
        """Activate/deactivate Input, QC, Output, Packing to match the step settings."""
        for field, _name, _suffix, flag in self._location_specs():
            loc_id = getattr(self, f'{field}_id')
            if loc_id:
                loc = StockLocation.objects.get(pk=loc_id)
                if self.active and loc.active and not flag and loc.has_stock(include_children=True):
                    raise ValidationError(
                        f'"{loc.complete_name}" still holds stock, so it cannot be deactivated.')
                StockLocation.objects.filter(pk=loc_id).update(active=self.active and flag)

    # -- persistence -------------------------------------------------------- #
    @transaction.atomic
    def save(self, *args, **kwargs):
        creating = self._state.adding
        old = None
        if not creating:
            old = Warehouse.objects.filter(pk=self.pk).values(
                'code', 'active', 'reception_steps', 'delivery_steps').first()

        super().save(*args, **kwargs)

        if creating:
            self._create_locations()
            return

        if old['code'] != self.code and self.view_location_id:
            view = StockLocation.objects.get(pk=self.view_location_id)
            view.name = self.code          # save() rebuilds complete_name for the subtree
            view.save()

        if old['active'] != self.active and self.view_location_id:
            view = StockLocation.objects.get(pk=self.view_location_id)
            view.descendants(include_self=True).update(active=self.active)

        steps_changed = (old['active'], old['reception_steps'], old['delivery_steps']) != (
            self.active, self.reception_steps, self.delivery_steps)
        if steps_changed:
            self._sync_step_locations()
        # Also re-sync when a type is missing or has no default location, so a save repairs it.
        if steps_changed or old['code'] != self.code or self._picking_types_need_repair():
            self._sync_picking_types()
            self._sync_routes()


